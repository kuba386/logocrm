import { describe, expect, it } from 'vitest'
import { amountInWords, somWords } from './amount-words'

describe('somWords', () => {
  it.each([
    [0, 'ноль'],
    [1, 'один'],
    [2, 'два'],
    [11, 'одиннадцать'],
    [19, 'девятнадцать'],
    [20, 'двадцать'],
    [21, 'двадцать один'],
    [100, 'сто'],
    [105, 'сто пять'],
    [999, 'девятьсот девяносто девять'],
    [1000, 'одна тысяча'],
    [2000, 'две тысячи'],
    [4500, 'четыре тысячи пятьсот'],
    [5000, 'пять тысяч'],
    [11000, 'одиннадцать тысяч'],
    [14000, 'четырнадцать тысяч'],
    [21000, 'двадцать одна тысяча'],
    [22000, 'двадцать две тысячи'],
    [111000, 'сто одиннадцать тысяч'],
    [112000, 'сто двенадцать тысяч'],
    [1_000_000, 'один миллион'],
    [2_000_001, 'два миллиона один'],
    [5_000_000, 'пять миллионов'],
    [1_234_567, 'один миллион двести тридцать четыре тысячи пятьсот шестьдесят семь'],
    [3_000_000_000, 'три миллиарда'],
    [1_000_001_000, 'один миллиард одна тысяча'],
  ])('%i → «%s»', (som, words) => {
    expect(somWords(som)).toBe(words)
  })

  it('отказывает на дроби и отрицательных', () => {
    expect(() => somWords(1.5)).toThrow(TypeError)
    expect(() => somWords(-1)).toThrow(TypeError)
  })
})

describe('amountInWords', () => {
  it('целые сомы — «00 тыйын», с заглавной', () => {
    expect(amountInWords(550_000)).toBe('Пять тысяч пятьсот сом 00 тыйын')
  })

  it('тыйыны двумя цифрами', () => {
    expect(amountInWords(1205)).toBe('Двенадцать сом 05 тыйын')
    expect(amountInWords(99)).toBe('Ноль сом 99 тыйын')
  })

  it('крупная сумма с тысячами женского рода', () => {
    expect(amountInWords(2_100_050)).toBe('Двадцать одна тысяча сом 50 тыйын')
  })

  it('возврат — «Минус»', () => {
    expect(amountInWords(-50_000)).toBe('Минус пятьсот сом 00 тыйын')
  })

  it('не принимает дробные тыйыны', () => {
    expect(() => amountInWords(10.5)).toThrow(TypeError)
  })
})
