-- =============================================================================
-- 0044_attendance_comment_privacy.sql — закрыть от родителя свободный текст
-- отметки посещения (этап 7c, попутное решение владельца 20.09.2026)
--
-- attendance.comment — то же самое, что students.notes, lessons.notes и
-- payers.notes (0031): внутренняя пометка стойки и специалиста, а не текст
-- для семьи («мама опять опоздала», «пришёл голодный, плакал»). Во всём
-- остальном проекте такой текст о семье закрыт от родителя; эта колонка
-- осталась случайным исключением, а не решённым.
--
-- Решения:
--   Р1. attendance_parent_read снимается целиком, тем же приёмом, что
--       снятие tenant_finance_select в 0031: роли доступна не колонка, а
--       узкая функция. Колоночные гранты не годятся — Postgres не даёт
--       «этот столбец виден одной роли по одному условию, а другой по
--       другому» в границах одной таблицы (ADR-005).
--   Р2. Замена родителю уже есть: student_attendance_brief (0043) — дата,
--       статус, признак пропуска, без comment/price_tiyin/subscription_id/
--       marked_by. Написана независимо от этого решения и уже покрывает
--       единственный существующий сценарий (месячный отчёт).
--   Р3. Отклонённая альтернатива — уровень 1 из ADR-005, вынести comment в
--       отдельную таблицу attendance_notes, сохранив родителю прямое
--       чтение дат и статусов. Не выбрана: это переписывание
--       mark_attendance, mark_attendance_bulk, complete_lesson и панели
--       отметки ради одной колонки, тогда как узкая функция уже написана.
--       Цена решения: родитель вместе с comment теряет прямой доступ и к
--       price_tiyin, subscription_id, marked_by, самой дате и статусу —
--       их возвращает student_attendance_brief.
--   Р4. Это не активная утечка сегодня, но и не потому, что экран родителю
--       закрыт: /app/schedule он открывает, и от чтения comment его
--       удерживает условие рендера в React (isMine/canManage), а не RLS.
--       Серверный экшен, отдающий attendance, читает её правами
--       вызывающего уже сейчас — первая же правка условия показа унесла бы
--       комментарий вместе с датами. Гарантия переносится в RLS, где ей и
--       место.
--   Р5. Гранты на таблицу не меняются: grant select/insert и
--       grant update (status_id, comment) остаются у authenticated целиком
--       (0009/0010) — ролевое различие держит только RLS. teacher и
--       owner/admin/registrar не задеты ни одной строкой этой миграции.
-- =============================================================================

drop policy if exists attendance_parent_read on public.attendance;

-- Комментарий живёт в базе и виден в дашборде — в отличие от шапки файла
-- 0043, которая (неверно, миграции неизменяемы) обещает «это закроет
-- следующая миграция».
comment on column public.attendance.comment is
  'Внутренняя пометка стойки/специалиста, тот же класс, что students.notes и payers.notes (0031). Родителю не видна ни в этой колонке, ни через RLS с 0044 — его путь student_attendance_brief (0043), у которой этой колонки нет физически.';

-- Замыкает ссылку в обе стороны: шапка 0043 обещает «это закроет следующая
-- миграция» и не может быть исправлена (миграции неизменяемы). Кто смотрит
-- на функцию в дашборде, должен увидеть актуальное состояние здесь, а не
-- устаревшее обещание там.
comment on function public.student_attendance_brief(uuid, date, date) is
  'Посещения за период: дата занятия, статус, признак пропуска. Ни цены, ни абонемента, ни комментария к отметке — там свободный текст стойки. С 0044 это единственный путь родителя к посещаемости: прямой доступ к attendance закрыт (attendance_parent_read снята).';
