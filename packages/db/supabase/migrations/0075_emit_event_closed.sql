-- =============================================================================
-- 0075_emit_event_closed.sql — emit_event закрыта для клиента
--
-- Найдено при ревью 0073. emit_event(text, jsonb, uuid) (0001/0002) исполнялась
-- ролью authenticated и проверяла только auth.uid() и членство в центре, но не
-- тип события: любой участник центра, включая parent и teacher, мог через
-- PostgREST записать в outbox системное событие произвольного типа и с
-- произвольным payload (digest.daily, lesson.reminder, payment.received…), а
-- воркер доставил бы по нему сообщения владельцу или родителям.
--
-- Проверено на staging до миграции: emit_event — единственная функция,
-- порождающая события, у которой authenticated имел EXECUTE (emit_clinical_event,
-- emit_event_internal, emit_event_platform, emit_event_unchecked — без грантов).
-- Веб-приложение, n8n, tg-bot и сиды emit_event напрямую не зовут. Все функции,
-- чей код вызывает emit_event(, — SECURITY DEFINER (63 на staging, 68 имён по
-- всем миграциям, включая заменённые), то есть выполняются от владельца
-- функции и от гранта authenticated не зависят.
--
-- Решения (ревью плана — architect):
--   Р1. Только revoke. Тело функции, включая проверку членства, не меняется:
--       definer-RPC зовут её как раньше, а проверка центра остаётся вторым
--       рубежом. Гранта не остаётся ни у кого, кроме владельца.
--   Р2. Забор — в pgTAP, не в комментарии: ACL всех перегрузок emit_event через
--       aclexplode (ловит любую роль и будущую перегрузку, которая по default
--       privileges Supabase получила бы гранты); все вызывающие — definer,
--       владелец которых имеет EXECUTE; в вью, политиках, значениях по умолчанию
--       и триггерах вызовов нет — иначе они шли бы от роли пользователя и
--       падали бы молча под authenticated.
--   Р3. Пересчёт суммы поступлений при доставке (0073) остаётся: это защита в
--       глубину — payload собирают definer-RPC, и часть его полей задаёт
--       пользователь.
--   Р4. НЕ решено здесь (долг): service_role имеет INSERT/UPDATE/DELETE на
--       public.events (0024 снял права только с public/anon/authenticated).
--       Это серверный ключ, в приложении не используется (ADR-004, n8n/README:
--       «не service_role»); его утечка — полная компрометация и без events.
--       Писать «outbox закрыт от service_role» нельзя: закрыт EXECUTE
--       emit_event, табличные права — нет.
-- =============================================================================

revoke all on function public.emit_event(text, jsonb, uuid)
  from public, anon, authenticated, service_role;

comment on function public.emit_event(text, jsonb, uuid) is
  'Запись события в outbox из тел SECURITY DEFINER-функций (0001/0002). С 0075 не дверь клиента: EXECUTE только у владельца — иначе любой участник центра создавал бы системные события произвольного типа. Проверка членства в центре остаётся вторым рубежом. Клиентского вызова нет и быть не должно; бот и воркер пишут через emit_event_unchecked/_internal/_platform.';
