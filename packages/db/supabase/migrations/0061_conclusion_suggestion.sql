-- =============================================================================
-- 0061_conclusion_suggestion.sql — подсказка заключения из шкал speech_areas
--
-- Фаза 2 из трёх, обещанных в 0059 Р-заголовке. Владелец подтвердил порог
-- «нарушено» 24.09.2026: значение ≤ 2 на шкале 1–5. Подсказка никогда не
-- переопределяет diagnostics.conclusion_code (Р12 из 0059) и никогда не
-- проставляется в поле формы сама — специалист жмёт отдельную кнопку
-- «Применить» (apps/web).
--
-- Первый план — денормализованная таблица-кеш diagnostic_conclusion_suggestions
-- с триггером — ушёл на ревью архитектору и вернулся с 12 находками:
--   * каст jsonb внутри AFTER-триггера на нетипизированном speech_areas мог
--     уронить сохранение всей диагностики (22P02) на любом кривом значении;
--   * уровень ОНР из average(лексика,грамматика,связная_речь) путал тяжесть
--     местами (одна тяжело нарушенная область при остальных в норме давала
--     САМЫЙ ЛЁГКИЙ уровень) и структурно не может отличить ОНР I от ЗРР —
--     у функции нет возраста ребёнка на входе, а это ровно та пара кодов,
--     которую логопеды путают чаще всего;
--   * кеш протухает (смена эвристики не пересчитывает старые строки, нет
--     бэкфилла для уже существующих диагностик) и дублирует нужду в RLS,
--     экспорте, guard-списках и is_active-проверке, которых при вычислении
--     на чтении не существует вовсе.
--
-- Решение: вычислять на чтении. Только чистая функция — ни таблицы, ни
-- триггера, ни новой RLS-поверхности, ни строк в export/readonly-guard
-- списках (добавлять некуда — новых таблиц нет).
--
--   Р1. Уровень ОНР не угадывается: любое нарушение в
--       лексике/грамматике/связной речи даёт общий флаг onr_suspected, а не
--       код onr_1..onr_4 из справочника. Выбор уровня — клиническое решение
--       специалиста, не арифметика по трём шкалам.
--   Р2. Функция ТОТАЛЬНА: любое значение по ключу, которое не jsonb-число
--       в диапазоне [1,5] (строка, объект, массив, дробное вне диапазона,
--       NaN/Infinity с фронта, отсутствие ключа), трактуется как
--       «неизвестно» и уводит в null, а не бросает исключение и не
--       считается баллом. Свободный jsonb без констрейнта (0036) и открытый
--       публике вход record_diagnostic — не место для доверия форме.
--   Р3. 'zrr' никогда не предлагается: возрастная категория, не выводится
--       из баллов по пяти областям без даты рождения ребёнка на входе.
--       pgTAP проверяет не буквальную строку 'zrr', а закрытое множество
--       результатов функции (её там нет и быть не может).
--   Р4. 'onr_suspected' — служебное значение, не код speech_conclusions;
--       ниже — pgTAP-проверка, что оно не совпадает ни с одним реальным
--       кодом справочника (защита от будущей случайной коллизии).
--   Р5. security definer не нужен: функция не трогает ни одной таблицы —
--       чистая арифметика над переданным jsonb-аргументом, который вызывающий
--       и так уже мог видеть.
--   Р6. Источник истины — эта функция; packages/core/src/nosology.ts —
--       зеркало для мгновенной подсказки в форме, пока специалист печатает
--       баллы (без похода в базу на каждое изменение поля). Один и тот же
--       нумерованный список случаев — и в Vitest (nosology.test.ts), и в
--       pgTAP ниже; сегодня SQL-версию не вызывает ничего в приложении
--       (потребитель — будущий отчёт по нозологии), поэтому единственное,
--       что удерживает реализации от расхождения — именно совпадение
--       тестовых случаев, не общий вызывающий код.
--   Р7. Пять канонических русских ключей («звукопроизношение», «фонематика»,
--       «лексика», «грамматика», «связная речь») жёстко зашиты в обеих
--       реализациях — иначе не свести. pgTAP закрепляет их литералами;
--       разойдётся форма (apps/web) — упадёт CI, а не тихо замолчит
--       подсказка для новых записей.
--   Р8. norm никогда не предлагается (находка ревью написанного SQL):
--       функция не видит diagnostics.sounds — карту звуков, которую
--       специалист заполняет в той же форме. Пять шкал в норме при трёх
--       искажённых звуках дали бы кликабельную кнопку «Применить: Речь в
--       норме» — заключение, которое снимает проблему, не ставя её.
--       Дешевле и безопаснее не расширять сигнатуру, а не заявлять «норма»
--       вовсе: подсказка существует ради выбора между ФНР/ФФНР/ОНР, а
--       «норма» — решение, которое специалист принимает сам, глядя на всю
--       карту, не только на пять чисел.
--
-- Функция сегодня не вызывается из приложения (только из pgTAP) — честно
-- зафиксировано в Р6, не выдаётся за используемый путь.
-- =============================================================================

create or replace function public.suggest_speech_conclusion(p_speech_areas jsonb)
  returns text
  language sql
  immutable
  set search_path = ''
as $$
  with scores as (
    select
      case when jsonb_typeof(p_speech_areas -> 'звукопроизношение') = 'number'
        and (p_speech_areas ->> 'звукопроизношение')::numeric between 1 and 5
        then (p_speech_areas ->> 'звукопроизношение')::numeric end as z,
      case when jsonb_typeof(p_speech_areas -> 'фонематика') = 'number'
        and (p_speech_areas ->> 'фонематика')::numeric between 1 and 5
        then (p_speech_areas ->> 'фонематика')::numeric end as f,
      case when jsonb_typeof(p_speech_areas -> 'лексика') = 'number'
        and (p_speech_areas ->> 'лексика')::numeric between 1 and 5
        then (p_speech_areas ->> 'лексика')::numeric end as l,
      case when jsonb_typeof(p_speech_areas -> 'грамматика') = 'number'
        and (p_speech_areas ->> 'грамматика')::numeric between 1 and 5
        then (p_speech_areas ->> 'грамматика')::numeric end as g,
      case when jsonb_typeof(p_speech_areas -> 'связная речь') = 'number'
        and (p_speech_areas ->> 'связная речь')::numeric between 1 and 5
        then (p_speech_areas ->> 'связная речь')::numeric end as s
  )
  select case
    when z is null or f is null or l is null or g is null or s is null then null
    when l <= 2 or g <= 2 or s <= 2 then 'onr_suspected'
    when f <= 2 then 'ffnr'
    when z <= 2 then 'fnr'
    else null
  end
  from scores
$$;

comment on function public.suggest_speech_conclusion(jsonb) is
  'Подсказка заключения из пяти шкал speech_areas (0061), «нарушено» ≤ 2, шкала [1,5]. Тотальна — на нечисловых/отсутствующих/вне-диапазона значениях отдаёт null, не бросает. null также означает «нарушений не найдено» — norm никогда не предлагается (Р8): функция не видит diagnostics.sounds, а «норма» снимает проблему, а не ставит её. onr_suspected — не код speech_conclusions, только флаг «есть признаки ОНР, уровень определяет специалист». zrr не предлагается никогда — возрастная категория. Зеркало — packages/core/src/nosology.ts; сегодня функцию вызывает только pgTAP, не приложение (Р6). Immutable: смена эвристики требует create or replace и не пересчитывает индексы/matview, если они появятся поверх неё.';

revoke all on function public.suggest_speech_conclusion(jsonb) from public, anon;
grant execute on function public.suggest_speech_conclusion(jsonb) to authenticated;

