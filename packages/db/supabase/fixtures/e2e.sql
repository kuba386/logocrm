-- Прошедшие занятия Данияра — для чек-листа этапа 4 -----------------------------

-- Отметка посещения требует starts_at <= now() (lesson-panel.tsx,
-- canMarkAttendance) — фиксированная будущая дата, как у остальной
-- фикстуры (2027), этой проверке никогда не пройдёт. Учитель тот же, что
-- у Айлин (Нургуль) — для пункта 5 чек-листа (специалист отмечает своё).
--
-- Пять слотов встык (без разрыва) внутри [полночь по Бишкеку; now() - 15
-- минут], а не голых «now() - N часов»: sell_subscription без явной даты
-- берёт center_today() — «сегодня» по тому же Бишкеку (0010:256), и если
-- первое занятие датировано ВЧЕРА по Бишкеку (now() - 5 часов уходит за
-- полночь, если прогон стартовал в первые часы суток), кандидат для
-- списания не находится (s.starts_at <= v_lesson_date, 0010:861) —
-- «Отметить посещение» перестаёт списывать. Тот же класс бага, что чинили
-- в fix/0010-freeze-test-timezone-flake, только тут расходятся между
-- собой две даты внутри одного прогона CI, а не внутри одного теста.
--
-- Первая версия фикса (greatest на каждый слот независимо) не годится:
-- впритык к полуночи несколько занятий схлопывались в одну и ту же (или
-- пересекающуюся) отметку времени и падали на lessons_teacher_no_overlap
-- — у всех пяти один teacher_id. v_slot делит РЕАЛЬНО доступное окно на
-- пять частей вместо того, чтобы клэмпить каждую точку по отдельности:
-- слоты всегда встык, никогда не пересекаются, чем бы ни было now(). При
-- обычном прогоне (доступного времени с запасом) v_slot — те же 45 минут,
-- что и раньше; сожмётся только если фикстура стартовала на считанные
-- минуты позже полуночи Бишкека.
do $$
declare
  v_midnight  timestamptz :=
    date_trunc('day', now() at time zone 'Asia/Bishkek') at time zone 'Asia/Bishkek';
  v_end       timestamptz := now() - interval '15 minutes';
  v_available interval := greatest(v_end - v_midnight, interval '0');
  v_slot      interval := least(interval '45 minutes', v_available / 5);
  v_l1 timestamptz := v_end - v_slot * 5;
  v_l2 timestamptz := v_end - v_slot * 4;
  v_l3 timestamptz := v_end - v_slot * 3;
  v_l4 timestamptz := v_end - v_slot * 2;
  v_l5 timestamptz := v_end - v_slot * 1;
begin
  insert into public.lessons (id, center_id, service_id, teacher_id, student_id, starts_at, ends_at)
  values
    ('e0000000-0000-0000-0000-0000000a0001', 'e0000000-0000-0000-0000-0000000000c1',
     'e0000000-0000-0000-0000-0000000000f1', 'e0000000-0000-0000-0000-0000000000b1',
     'e0000000-0000-0000-0000-0000000000e2', v_l1, v_l1 + v_slot),
    ('e0000000-0000-0000-0000-0000000a0002', 'e0000000-0000-0000-0000-0000000000c1',
     'e0000000-0000-0000-0000-0000000000f1', 'e0000000-0000-0000-0000-0000000000b1',
     'e0000000-0000-0000-0000-0000000000e2', v_l2, v_l2 + v_slot),
    ('e0000000-0000-0000-0000-0000000a0003', 'e0000000-0000-0000-0000-0000000000c1',
     'e0000000-0000-0000-0000-0000000000f1', 'e0000000-0000-0000-0000-0000000000b1',
     'e0000000-0000-0000-0000-0000000000e2', v_l3, v_l3 + v_slot),
    ('e0000000-0000-0000-0000-0000000a0004', 'e0000000-0000-0000-0000-0000000000c1',
     'e0000000-0000-0000-0000-0000000000f1', 'e0000000-0000-0000-0000-0000000000b1',
     'e0000000-0000-0000-0000-0000000000e2', v_l4, v_l4 + v_slot),
    ('e0000000-0000-0000-0000-0000000a0005', 'e0000000-0000-0000-0000-0000000000c1',
     'e0000000-0000-0000-0000-0000000000f1', 'e0000000-0000-0000-0000-0000000000b1',
     'e0000000-0000-0000-0000-0000000000e2', v_l5, v_l5 + v_slot)
  on conflict (id) do nothing;
end $$;
