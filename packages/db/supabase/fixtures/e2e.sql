-- Прошедшие занятия Данияра — для чек-листа этапа 4 -----------------------------

-- Отметка посещения требует starts_at <= now() (lesson-panel.tsx,
-- canMarkAttendance) — фиксированная будущая дата, как у остальной
-- фикстуры (2027), этой проверке никогда не пройдёт. Учитель тот же, что
-- у Айлин (Нургуль) — для пункта 5 чек-листа (специалист отмечает своё).
--
-- Пять слотов встык, все ВЧЕРА по Бишкеку (не сегодня, не «now() - N
-- часов») — двух причин разом.
--
-- 1. sell_subscription без явной даты брал бы center_today() — «сегодня»
--    по Бишкеку (0010:256); занятие, датированное «now() - N часов»,
--    могло уйти на вчера, если фикстура применяется в первые часы суток —
--    кандидат для списания не находится (s.starts_at <= v_lesson_date,
--    0010:861), «Отметить посещение» перестаёт списывать. Тот же класс
--    бага, что чинили в fix/0010-freeze-test-timezone-flake, только тут
--    расходятся две даты внутри одного прогона CI, а не внутри теста.
--    Решение — не подстроить занятие под «сегодня», а держать И занятия,
--    И продажу абонемента на ОДНОЙ, всегда однозначной дате: явное вчера,
--    и в фикстуре, и в форме продажи (apps/web/e2e/attendance-
--    subscriptions.spec.ts явно проставляет #startsAt тем же вчера).
-- 2. Первая версия держала занятия в узком окне [полночь Бишкека; now()],
--    сжимая слоты, если фикстура применяется вскоре после полуночи — та
--    версия чинила и это, но роняла Playwright по-другому: слоты уезжали
--    на 00:00-01:xx утра, сетка расписания показывает рабочий диапазон
--    (08:00-20:00), карточка занятия физически не попадала в отрисованную
--    область, клик не находил элемент 90 секунд. Фиксированные дневные
--    часы вчера решают и это: занятие всегда в обычном рабочем диапазоне,
--    независимо от того, в какой час суток запустился прогон CI.
do $$
declare
  -- Конец последнего слота — 15:00 по Бишкеку вчера, назад пять слотов по
  -- 45 минут без разрыва (11:15-15:00). at time zone дважды — идиома
  -- проекта для «собрать timestamptz из даты и часа по времени центра»
  -- (см. financial_period_guard и close_month за обратное преобразование).
  v_end timestamptz := (
    date_trunc('day', now() at time zone 'Asia/Bishkek') - interval '1 day' + interval '15 hours'
  ) at time zone 'Asia/Bishkek';
  v_l1 timestamptz := v_end - interval '225 min';
  v_l2 timestamptz := v_end - interval '180 min';
  v_l3 timestamptz := v_end - interval '135 min';
  v_l4 timestamptz := v_end - interval '90 min';
  v_l5 timestamptz := v_end - interval '45 min';
begin
  insert into public.lessons (id, center_id, service_id, teacher_id, student_id, starts_at, ends_at)
  values
    ('e0000000-0000-0000-0000-0000000a0001', 'e0000000-0000-0000-0000-0000000000c1',
     'e0000000-0000-0000-0000-0000000000f1', 'e0000000-0000-0000-0000-0000000000b1',
     'e0000000-0000-0000-0000-0000000000e2', v_l1, v_l1 + interval '45 min'),
    ('e0000000-0000-0000-0000-0000000a0002', 'e0000000-0000-0000-0000-0000000000c1',
     'e0000000-0000-0000-0000-0000000000f1', 'e0000000-0000-0000-0000-0000000000b1',
     'e0000000-0000-0000-0000-0000000000e2', v_l2, v_l2 + interval '45 min'),
    ('e0000000-0000-0000-0000-0000000a0003', 'e0000000-0000-0000-0000-0000000000c1',
     'e0000000-0000-0000-0000-0000000000f1', 'e0000000-0000-0000-0000-0000000000b1',
     'e0000000-0000-0000-0000-0000000000e2', v_l3, v_l3 + interval '45 min'),
    ('e0000000-0000-0000-0000-0000000a0004', 'e0000000-0000-0000-0000-0000000000c1',
     'e0000000-0000-0000-0000-0000000000f1', 'e0000000-0000-0000-0000-0000000000b1',
     'e0000000-0000-0000-0000-0000000000e2', v_l4, v_l4 + interval '45 min'),
    ('e0000000-0000-0000-0000-0000000a0005', 'e0000000-0000-0000-0000-0000000000c1',
